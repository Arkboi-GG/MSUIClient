    /// <summary>
    /// The formatted line for this viewer, or null if the emote id/gender combo
    /// resolves to nothing (an id outside the 169 known emotes, or every slot
    /// in the relevant block is unset). hasTarget/viewerIsTarget/viewerIsEmoter
    /// pick the relative slot; emoterIsFemale picks the block, with a fallback
    /// to the male block on a zero (unset) female slot.
    /// </summary>
    public static string? Resolve(int emoteId, bool hasTarget, bool viewerIsEmoter,
        bool viewerIsTarget, bool emoterIsFemale, string emoterName, string targetName)
    {
        if (!SlotsById.TryGetValue(emoteId, out int[]? slots)) return null;

        int relative = viewerIsEmoter ? 2 : (hasTarget && viewerIsTarget ? 1 : 0);
        int block = (hasTarget ? 0 : 4) + (emoterIsFemale ? 8 : 0);
        int textDataId = slots[block + relative];
        if (textDataId == 0 && emoterIsFemale) textDataId = slots[(block - 8) + relative];
        if (textDataId == 0 || !Templates.TryGetValue(textDataId, out string? template)) return null;

        // Argument order matches the DBC's own authored templates: the bystander
        // form is always "<emoter> ... <target>", the emoter's own view only
        // ever needs the target ("You wave at %s."), and the target's own view
        // only ever needs the emoter ("%s waves at you.").
        string[] args = viewerIsEmoter
            ? (hasTarget ? new[] { targetName } : System.Array.Empty<string>())
            : viewerIsTarget && hasTarget
                ? new[] { emoterName }
                : hasTarget ? new[] { emoterName, targetName } : new[] { emoterName };

        int arg = 0;
        var sb = new System.Text.StringBuilder();
        for (int i = 0; i < template.Length; i++)
        {
            if (template[i] == '%' && i + 1 < template.Length && template[i + 1] == 's' && arg < args.Length)
            { sb.Append(args[arg++]); i++; }
            else sb.Append(template[i]);
        }
        return sb.ToString();
    }
