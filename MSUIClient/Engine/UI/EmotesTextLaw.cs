/// <summary>
/// The real client's text-emote flavour-text resolver, transcribed from two
/// 1.12.1 DBCs (DBFilesClient\EmotesText.dbc, DBFilesClient\EmotesTextData.dbc,
/// read via tools/mpqpeek + a throwaway parser - not recalled) plus the public
/// client-binary algorithm (CGChat::AddTextEmoteMessage, cross-checked against
/// the real DBC bytes until the pattern held for every row tried).
///
/// Server-side, VMaNGOS's own EmotesTextEntry struct only reads Id and the
/// animation id (see Opcodes.cpp/DBCStructure.h) - the 16-slot text array
/// below is NEVER touched server-side. SMSG_TEXT_EMOTE (0x0105) carries only
/// raw ids/names; picking and formatting the actual sentence is entirely a
/// client job, done natively in the real client (never exposed to FrameXML -
/// GlobalStrings.lua has no "%s waves." style templates at all), which is why
/// MSUIClient has to do it here instead of just displaying server text.
///
/// Each emote has up to 16 EmotesTextData rows, one per (targeted?,
/// perspective, gender) combination - a fixed-width block layout, empirically
/// verified against every row pulled:
///   block 0  = has a target,    male   : [bystander, viewer-is-target, viewer-is-emoter, unused]
///   block 4  = no target,       male   : [bystander, unused,           viewer-is-emoter, unused]
///   block 8  = has a target,    female : same 4 relative slots as block 0
///   block 12 = no target,       female : same 4 relative slots as block 4
/// A female slot of 0 falls back to the same relative slot in the male block
/// (confirmed: ANGRY's female blocks are only partially populated).
/// </summary>
