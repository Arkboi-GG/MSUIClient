    /// <summary>Explode a PKWARE-DCL stream to its decompressed bytes.</summary>
    public static byte[] Explode(byte[] input, int offset, int count)
        => new Worker(input, offset, count).Run();

    private sealed class Worker
    {
        private readonly byte[] _in;
        private readonly int _base;
        private readonly int _inBytes;
        private int _inPos;

        private uint _bitBuff;
        private int _extraBits;

        private int _ctype;
        private int _dsizeBits;
        private uint _dsizeMask;

        private readonly byte[] _lengthCodes  = new byte[0x100];
        private readonly byte[] _distPosCodes = new byte[0x100];
        private readonly byte[] _chBitsAsc    = (byte[])ChBitsAscConst.Clone();
        private readonly byte[] _offs2C34 = new byte[0x100];
        private readonly byte[] _offs2D34 = new byte[0x100];
        private readonly byte[] _offs2E34 = new byte[0x80];
        private readonly byte[] _offs2EB4 = new byte[0x100];

        private readonly byte[] _out = new byte[0x2204];
        private int _outPos;
        private readonly MemoryStream _result = new();

        public Worker(byte[] input, int offset, int count)
        {
            _in = input; _base = offset; _inBytes = count;
        }

        public byte[] Run()
        {
            if (_inBytes <= 4)
                throw new InvalidDataException("PKWARE explode: input too short.");

            _ctype     = _in[_base + 0];
            _dsizeBits = _in[_base + 1];
            _bitBuff   = _in[_base + 2];
            _extraBits = 0;
            _inPos     = 3;

            if (_dsizeBits < 4 || _dsizeBits > 6)
                throw new InvalidDataException($"PKWARE explode: invalid dictionary-size bits {_dsizeBits}.");
            _dsizeMask = 0xFFFFu >> (0x10 - _dsizeBits);

            if (_ctype != CmpBinary)
                GenAscTabs();

            GenDecodeTabs(_lengthCodes,  LenCode,  LenBits);
            GenDecodeTabs(_distPosCodes, DistCode, DistBits);

            uint r = Expand();
            if (r == 0x306)
                throw new InvalidDataException("PKWARE explode: corrupt stream.");
            return _result.ToArray();
        }

        private static void GenDecodeTabs(byte[] positions, byte[] startIndexes, byte[] lengthBits)
        {
            for (int i = 0; i < startIndexes.Length; i++)
            {
                int length = 1 << lengthBits[i];
                for (int index = startIndexes[i]; index < 0x100; index += length)
                    positions[index] = (byte)i;
            }
        }

        private void GenAscTabs()
        {
            for (int count = 0xFF; count >= 0; count--)
            {
                int chcode  = ChCodeAsc[count];
                int bitsAsc = _chBitsAsc[count];
                int acc, add;

                if (bitsAsc <= 8)
                {
                    add = 1 << bitsAsc; acc = chcode;
                    do { _offs2C34[acc] = (byte)count; acc += add; } while (acc < 0x100);
                }
                else if ((acc = (chcode & 0xFF)) != 0)
                {
                    _offs2C34[acc] = 0xFF;
                    if ((chcode & 0x3F) != 0)
                    {
                        bitsAsc -= 4; _chBitsAsc[count] = (byte)bitsAsc;
                        add = 1 << bitsAsc; acc = chcode >> 4;
                        do { _offs2D34[acc] = (byte)count; acc += add; } while (acc < 0x100);
                    }
                    else
                    {
                        bitsAsc -= 6; _chBitsAsc[count] = (byte)bitsAsc;
                        add = 1 << bitsAsc; acc = chcode >> 6;
                        do { _offs2E34[acc] = (byte)count; acc += add; } while (acc < 0x80);
                    }
                }
                else
                {
                    bitsAsc -= 8; _chBitsAsc[count] = (byte)bitsAsc;
                    add = 1 << bitsAsc; acc = chcode >> 8;
                    do { _offs2EB4[acc] = (byte)count; acc += add; } while (acc < 0x100);
                }
            }
        }

        // WasteBits (explode.c): consume nBits, refilling from input as needed.
        private int WasteBits(int nBits)
        {
            if (nBits <= _extraBits) { _extraBits -= nBits; _bitBuff >>= nBits; return DclOk; }
            _bitBuff >>= _extraBits;
            if (_inPos == _inBytes) return DclStreamEnd;   // whole input is buffered; none left
            _bitBuff |= (uint)(_in[_base + _inPos++] << 8);
            _bitBuff >>= (nBits - _extraBits);
            _extraBits = (_extraBits - nBits) + 8;
            return DclOk;
        }

        private uint DecodeLit()
        {
            if ((_bitBuff & 1) != 0)
            {
                if (WasteBits(1) != 0) return 0x306;
                int lengthCode = _lengthCodes[_bitBuff & 0xFF];
                if (WasteBits(LenBits[lengthCode]) != 0) return 0x306;

                int elb = ExLenBits[lengthCode];
                if (elb != 0)
                {
                    int extra = (int)(_bitBuff & (uint)((1 << elb) - 1));
                    if (WasteBits(elb) != 0)
                    {
                        if ((lengthCode + extra) != 0x10E) return 0x306;
                    }
                    lengthCode = LenBase[lengthCode] + extra;
                }
                return (uint)(lengthCode + 0x100);
            }

            if (WasteBits(1) != 0) return 0x306;

            if (_ctype == CmpBinary)
            {
                uint ub = _bitBuff & 0xFF;
                if (WasteBits(8) != 0) return 0x306;
                return ub;
            }

            int value;
            if ((_bitBuff & 0xFF) != 0)
            {
                value = _offs2C34[_bitBuff & 0xFF];
                if (value == 0xFF)
                {
                    if ((_bitBuff & 0x3F) != 0)
                    {
                        if (WasteBits(4) != 0) return 0x306;
                        value = _offs2D34[_bitBuff & 0xFF];
                    }
                    else
                    {
                        if (WasteBits(6) != 0) return 0x306;
                        value = _offs2E34[_bitBuff & 0x7F];
                    }
                }
            }
            else
            {
                if (WasteBits(8) != 0) return 0x306;
                value = _offs2EB4[_bitBuff & 0xFF];
            }
            return WasteBits(_chBitsAsc[value]) != 0 ? 0x306 : (uint)value;
        }

        private uint DecodeDist(uint repLength)
        {
            int code = _distPosCodes[_bitBuff & 0xFF];
            if (WasteBits(DistBits[code]) != 0) return 0;

            uint distance;
            if (repLength == 2)
            {
                distance = (uint)((code << 2) | (int)(_bitBuff & 0x03));
                if (WasteBits(2) != 0) return 0;
            }
            else
            {
                distance = (uint)((code << _dsizeBits) | (int)(_bitBuff & _dsizeMask));
                if (WasteBits(_dsizeBits) != 0) return 0;
            }
            return distance + 1;
        }

        private uint Expand()
        {
            _outPos = 0x1000;   // first 0x1000 bytes are the sliding-window history
            uint result;
            while ((result = DecodeLit()) < 0x305)
            {
                if (result >= 0x100)
                {
                    uint repLength = result - 0xFE;
                    uint minusDist = DecodeDist(repLength);
                    if (minusDist == 0) { result = 0x306; break; }

                    int target = _outPos;
                    int source = target - (int)minusDist;
                    _outPos += (int)repLength;
                    // byte-by-byte: a repetition may overlap the current position
                    for (uint k = 0; k < repLength; k++)
                        _out[target++] = _out[source++];
                }
                else
                {
                    _out[_outPos++] = (byte)result;
                }

                if (_outPos >= 0x2000)
                {
                    _result.Write(_out, 0x1000, 0x1000);
                    Array.Copy(_out, 0x1000, _out, 0, _outPos - 0x1000);  // overlap-safe (memmove)
                    _outPos -= 0x1000;
                }
            }
            _result.Write(_out, 0x1000, _outPos - 0x1000);
            return result;
        }
    }
